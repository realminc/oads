#!/usr/bin/env python3
"""Generate schema-owned dataset surfaces for oads.

`tool/gen/ds/schema/packs.json` owns every pack manifest, split type,
config struct, dispatch arm, facade export, Python matrix wrapper, license
row, and dataset table. This generator emits them; handwritten loader files
keep only decode bodies and custom `Dataset` impls.

    python3 tool/gen/ds/generate.py          # write all generated files
    python3 tool/gen/ds/generate.py --check  # verify no drift, exit 1 on diff
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCHEMA = Path(__file__).resolve().parent / "schema" / "packs.json"

RS_BANNER = "// @generated by tool/gen/ds/generate.py — edit tool/gen/ds/schema/packs.json instead.\n"
PY_BANNER = "# @generated by tool/gen/ds/generate.py — edit tool/gen/ds/schema/packs.json instead.\n"
MD_BANNER = "<!-- @generated by tool/gen/ds/generate.py — edit tool/gen/ds/schema/packs.json instead. -->\n"

INTERNAL_MODULES = ["csv", "extract", "idx", "midi", "npy", "wav"]
CORE_EXPORTS = [
	("idx", ["IdxSplit"]),
	(
		"pack",
		[
			"FetchProgress",
			"Pack",
			"PackFile",
			"TerminalProgress",
			"data_root",
			"ensure_pack",
			"ensure_pack_with_progress",
			"hash_file",
		],
	),
]

GENERIC_EXPR = {
	"split": "config.split",
	"cache_dir": "config.cache_dir.clone()",
	"normalize": "config.normalize",
	"count": "config.count",
}


def load_schema() -> dict:
	return json.loads(SCHEMA.read_text())


def underscored(value: int) -> str:
	digits = str(value)
	groups = []
	while digits:
		groups.append(digits[-3:])
		digits = digits[:-3]
	return "_".join(reversed(groups))


def doc_lines(text: str, prefix: str = "///") -> list[str]:
	return [f"{prefix} {line}".rstrip() for line in text.split("\n")]


def rust_name(pack: dict) -> str:
	return pack.get("const_name", f"{pack['name'].upper()}_PACK")


def gen_loader(pack: dict) -> str:
	out = [RS_BANNER, ""]
	out.append("use oa::{Engine, Result};\n")
	if any("PathBuf" in field["type"] for field in pack["config"]):
		out.append("use std::path::PathBuf;\n")
	if pack["split"] and pack["split"]["kind"] == "idx":
		out.append("use crate::idx::IdxSplit;\n")
	out.append("use crate::pack::{FetchProgress, Pack, PackFile};\n\n")

	# Manifest.
	out.append(f"pub(crate) const {rust_name(pack)}: Pack = Pack {{\n")
	out.append(f'\tname: "{pack["name"]}",\n')
	out.append(f'\tversion: "{pack["version"]}",\n')
	out.append(f'\tlicense: "{pack["license"]}",\n')
	out.append("\tfiles: &[\n")
	for entry in pack["files"]:
		out.append("\t\tPackFile {\n")
		out.append(f'\t\t\tname: "{entry["name"]}",\n')
		out.append(f'\t\t\tsize: {underscored(entry["size"])},\n')
		out.append(f'\t\t\tshake256: "{entry["shake256"]}",\n')
		if len(entry["urls"]) == 1:
			out.append(f'\t\t\turls: &["{entry["urls"][0]}"],\n')
		else:
			out.append("\t\t\turls: &[\n")
			for url in entry["urls"]:
				out.append(f'\t\t\t\t"{url}",\n')
			out.append("\t\t\t],\n")
		out.append("\t\t},\n")
	out.append("\t],\n};\n")

	# Pack consts.
	for const in pack.get("consts", []):
		out.append("\n")
		out.extend(line + "\n" for line in doc_lines(const["doc"]))
		out.append(f"pub const {const['name']}: {const['type']} = {const['value']};\n")

	# Split type.
	split = pack["split"]
	if split and split["kind"] == "idx":
		out.append("\n")
		out.extend(line + "\n" for line in doc_lines(split["doc"]))
		out.append(f"pub type {pack['class']}Split = IdxSplit;\n")
	elif split and split["kind"] == "enum":
		out.append("\n")
		out.extend(line + "\n" for line in doc_lines(split["doc"]))
		out.append("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]\n")
		out.append(f"pub enum {pack['class']}Split {{\n")
		for variant in split["variants"]:
			out.extend("\t" + line + "\n" for line in doc_lines(variant["doc"]))
			if variant.get("default"):
				out.append("\t#[default]\n")
			out.append(f"\t{variant['name']},\n")
		out.append("}\n")

	# Config.
	cls = pack["class"]
	out.append("\n")
	out.extend(
		line + "\n"
		for line in doc_lines(
			f"Load options for [`{cls}`][crate::{pack['domain']}::{pack['name']}::{cls}]."
		)
	)
	# `Default` derives only when every field default is the type's own
	# `Default::default()` value; enum/nonzero defaults need the manual impl.
	if all(field["default"] in ("None", "Default::default()") for field in pack["config"]):
		out.append("#[derive(Clone, Debug, Default)]\n")
	else:
		out.append("#[derive(Clone, Debug)]\n")
	out.append(f"pub struct {cls}Config {{\n")
	for field in pack["config"]:
		out.extend("\t" + line + "\n" for line in doc_lines(field["doc"]))
		out.append(f"\tpub {field['name']}: {field['type']},\n")
	out.append("}\n\n")
	if all(field["default"] in ("None", "Default::default()") for field in pack["config"]):
		pass
	else:
		out.append(f"impl Default for {cls}Config {{\n")
		out.append("\tfn default() -> Self {\n")
		out.append("\t\tSelf {\n")
		for field in pack["config"]:
			out.append(f"\t\t\t{field['name']}: {field['default']},\n")
		out.append("\t\t}\n\t}\n}\n\n")
	out.append(f"impl {cls}Config {{\n")
	out.append("\t/// Construct the record with its default state.\n")
	out.append("\t#[inline]\n\t#[must_use]\n")
	out.append("\tpub fn new() -> Self {\n")
	out.append("\t\tSelf::default()\n\t}\n}\n")

	# Engineless/explicit load family over handwritten load_with_progress_on.
	out.append(f"\nimpl super::{cls} {{\n")
	out.append("\t/// Decode the selected split and upload it on this thread's\n")
	out.append("\t/// default engine.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns an error when the default engine cannot be\n")
	out.append("\t/// initialized, plus the errors of\n")
	out.append("\t/// [`load_on`](Self::load_on).\n")
	out.append("\t#[inline]\n")
	out.append(f"\tpub fn load(config: &{cls}Config) -> Result<Self> {{\n")
	out.append("\t\tSelf::load_on(&Engine::current()?, config)\n")
	out.append("\t}\n\n")
	out.append("\t/// Decode the selected split and upload it on `engine`.\n")
	out.append("\t///\n")
	out.append("\t/// This is the [`load`](Self::load) contract evaluated on\n")
	out.append("\t/// `engine` instead of this thread's default engine.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns the errors of\n")
	out.append("\t/// [`load_with_progress_on`](Self::load_with_progress_on).\n")
	out.append("\t#[inline]\n")
	out.append(f"\tpub fn load_on(engine: &Engine, config: &{cls}Config) -> Result<Self> {{\n")
	out.append("\t\tSelf::load_with_progress_on(engine, config, &mut |_| true)\n")
	out.append("\t}\n\n")
	out.append("\t/// [`load`](Self::load) with a fetch progress callback.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns an error when the default engine cannot be\n")
	out.append("\t/// initialized, plus the errors of\n")
	out.append("\t/// [`load_with_progress_on`](Self::load_with_progress_on).\n")
	out.append("\t#[inline]\n")
	out.append("\tpub fn load_with_progress(\n")
	out.append(f"\t\tconfig: &{cls}Config,\n")
	out.append("\t\tprogress: &mut impl FnMut(FetchProgress) -> bool,\n")
	out.append("\t) -> Result<Self> {\n")
	out.append("\t\tSelf::load_with_progress_on(&Engine::current()?, config, progress)\n")
	out.append("\t}\n}\n")
	return "".join(out)


def dispatch_expr(pack: dict, field: dict) -> str:
	generic = field.get("generic")
	if generic == "split":
		if pack["split"]["kind"] == "idx":
			return "config.split"
		mapping = pack["split"]["dispatch"]
		arms = ",\n\t\t\t\t".join(
			f"IdxSplit::{src} => crate::{pack['domain']}::{pack['name']}::{pack['class']}Split::{dst}"
			for src, dst in mapping.items()
		)
		return "match config.split {\n\t\t\t\t" + arms + ",\n\t\t\t}"
	if generic is None:
		return field["dispatch"]
	return GENERIC_EXPR[generic]


def gen_dispatch(packs: list[dict]) -> str:
	out = [RS_BANNER, ""]
	out.append("use oa::{Error, Result};\n\n")
	out.append("use crate::IdxSplit;\n")
	out.append("use crate::decode::{DecodeConfig, Decoded};\n")
	out.append("use crate::pack::{FetchProgress, Pack};\n\n")

	out.append("pub(crate) fn manifest_of(name: &str) -> Result<&'static Pack> {\n")
	out.append("\tmatch name {\n")
	for pack in packs:
		out.append(
			f'\t\t"{pack["name"]}" => Ok(&crate::{pack["domain"]}::{pack["name"]}::{rust_name(pack)}),\n'
		)
	out.append("\t\t_ => Err(Error::invalid_argument(format!(\n")
	out.append('\t\t\t"unknown dataset pack \'{name}\'"\n')
	out.append("\t\t))),\n\t}\n}\n\n")

	out.append("pub(crate) fn load_of(\n")
	out.append("\tname: &str,\n")
	out.append("\tconfig: &DecodeConfig,\n")
	out.append("\tprogress: &mut impl FnMut(FetchProgress) -> bool,\n")
	out.append(") -> Result<Decoded> {\n")
	out.append("\tmatch name {\n")
	for pack in packs:
		cls = pack["class"]
		call = "decode_with_progress" if pack["progress"] else "decode"
		out.append(
			f'\t\t"{pack["name"]}" => crate::{pack["domain"]}::{pack["name"]}::{cls}::{call}(\n'
		)
		out.append(f"\t\t\t&crate::{pack['domain']}::{pack['name']}::{cls}Config {{\n")
		for field in pack["config"]:
			out.append(f"\t\t\t\t{field['name']}: {dispatch_expr(pack, field)},\n")
		out.append("\t\t\t},\n")
		if pack["progress"]:
			out.append("\t\t\tprogress,\n")
		out.append("\t\t),\n")
	out.append("\t\t_ => Err(Error::invalid_argument(format!(\n")
	out.append('\t\t\t"unknown dataset pack \'{name}\'"\n')
	out.append("\t\t))),\n\t}\n}\n")
	return "".join(out)


def exported_names(pack: dict) -> list[str]:
	names = [pack["class"], f"{pack['class']}Config"]
	if pack["split"]:
		names.append(f"{pack['class']}Split")
	names.extend(pack.get("extra_exports", []))
	for const in pack.get("consts", []):
		if const.get("export"):
			names.append(const["name"])
	return sorted(names)


def gen_facade(
	domain: str, doc: str, packs: list[dict], internal_modules: list[str] | None = None
) -> str:
	internal_modules = internal_modules or []
	out = [RS_BANNER, ""]
	for line in doc.split("\n"):
		prefix = "//!" if line.startswith("//!") else "//!"
		out.append(f"{prefix} {line.removeprefix('//!').lstrip()}".rstrip() + "\n")
	out.append("\n")
	for module in internal_modules:
		out.append(f"pub(crate) mod {module};\n")
	for pack in packs:
		out.append(f"pub mod {pack['name']};\n")
	out.append("\n")
	for pack in packs:
		names = ", ".join(exported_names(pack))
		out.append(f"pub use {pack['name']}::{{{names}}};\n")
	return "".join(out)


def gen_lib_rs(schema: dict, packs: list[dict]) -> str:
	out = [RS_BANNER, ""]
	out.append("//! Realm dataset packs and typed loaders for OA.\n")
	out.append("//!\n")
	out.append("//! `pack` is the transport layer: immutable manifests, `OA_DATA_DIR` cache\n")
	out.append("//! resolution, fetch, and SHAKE256-256 verification. Each typed loader —\n")
	out.append("//! grouped by domain under [`audio`], [`image`], [`text`], and [`video`] —\n")
	out.append("//! materializes its pack and implements [`oa::data::Dataset`], so\n")
	out.append("//! [`oa::data::DataLoader`], [`oa::data::collate`], and subset/split\n")
	out.append("//! operations work unchanged.\n\n")
	domains = sorted(schema["domains"])
	out.append(f"pub mod {domains[0]};\n")
	out.append("pub mod decode;\n")
	for module in INTERNAL_MODULES:
		out.append(f"mod {module};\n")
	out.append('\n#[path = "decode_dispatch.gen.rs"]\nmod decode_dispatch;\n\n')
	for module in domains[1:]:
		out.append(f"pub mod {module};\n")
	out.append("pub mod pack;\n\n")

	for domain in domains:
		names = []
		for pack in packs:
			if pack["domain"] == domain:
				names.extend(exported_names(pack))
		out.append(f"pub use {domain}::{{{', '.join(sorted(names))}}};\n")
	for module, names in CORE_EXPORTS:
		out.append(f"pub use {module}::{{{', '.join(names)}}};\n")
	return "".join(out)


def py_const_expr(const: dict) -> str | None:
	if const["type"].startswith("[&str"):
		names = re.findall(r'"([^"]+)"', const["value"])
		return "(" + ", ".join(f'"{n}"' for n in names) + ")"
	return None


def gen_python_loader(pack: dict) -> str | None:
	py = pack["python"]
	if py["contract"] != "matrix":
		return None
	doc = py["doc"]
	header = f'"""{doc}"""\n' if "\n" not in doc else f'"""{doc}\n"""\n'
	out = [header + "\n"]
	unsplit = py.get("unsplit", False)
	if unsplit:
		out.append("from pathlib import Path\n\n")
		out.append("from .. import _native\n")
		out.append("from .._progress import resolve\n")
		out.append("from ..dataset import MatrixDataset, matrix\n")
	else:
		out.append("from .. import _native\n")
		out.append("from ..dataset import MatrixDataset\n")
	out.append(f"\n\nclass {pack['class']}(MatrixDataset):\n")
	out.append(f'\tPACK = _native.pack_manifest("{pack["name"]}")\n')
	if pack["python"]["feature"] != "images":
		out.append(f'\tFEATURE = "{py["feature"]}"\n')
	if py.get("label", "labels") != "labels":
		out.append(f'\tLABEL = "{py["label"]}"\n')
	for name in py.get("consts", []):
		const = next(c for c in pack["consts"] if c["name"] == name)
		expr = py_const_expr(const)
		if expr:
			out.append(f"\t{name} = {expr}\n")
	if unsplit:
		load_doc = py.get(
			"load_doc",
			"Fetch, verify, decode, and upload the full pack.\n\n"
			"\tnormalize=True scales features into the pack's canonical unit\n"
			"\trange; normalize=False keeps raw f32 values. progress=True renders\n"
			"\tthe download bar.",
		)
		out.append(
			f"""
	@classmethod
	def load(cls, engine=None, cache_dir=None, normalize: bool = True, progress=True):
		\"\"\"{load_doc}
		\"\"\"
		fields = _native.load(
			cls.PACK["name"],
			# The pack carries one unsplit set; the native split argument
			# only accepts train/test and is ignored for this loader.
			split="train",
			normalize=normalize,
			cache_dir=str(Path(cache_dir)) if cache_dir else None,
			progress=resolve(progress),
		)
		return cls(
			matrix(fields[cls.FEATURE], engine),
			matrix(fields[cls.LABEL], engine),
			"all",
		)
"""
		)
	feature = py["feature"]
	feature_doc = py.get(
		"feature_doc", f"Full {feature} matrix on the owning engine; alias of `x`."
	)
	out.append("\n\t@property\n")
	out.append(f"\tdef {feature}(self):\n")
	out.append(f'\t\t"""{feature_doc}"""\n')
	out.append("\t\treturn self.x\n")
	label = py.get("label")
	if label and label != "labels":
		label_doc = py.get(
			"label_doc", f"Full {label} matrix on the owning engine; alias of `labels`."
		)
		out.append("\n\t@property\n")
		out.append(f"\tdef {label}(self):\n")
		out.append(f'\t\t"""{label_doc}"""\n')
		out.append("\t\treturn self.labels\n")
	return "".join(out)


def gen_python_init(domain: str, doc: str, packs: list[dict]) -> str:
	header = f'"""{doc}"""\n' if "\n" not in doc else f'"""{doc}\n"""\n'
	out = [header + "\n"]
	for pack in sorted(packs, key=lambda p: p["class"]):
		out.append(f"from .{pack['name']} import {pack['class']}\n")
	all_names = ", ".join(
		f'"{p["class"]}"' for p in sorted(packs, key=lambda p: p["class"])
	)
	out.append(f"\n__all__ = [{all_names}]\n")
	return "".join(out)


def gen_python_root(schema: dict, packs: list[dict], version: str) -> str:
	out = ['"""oads — Realm dataset packs and typed loaders for OA.\n\n']
	out.append("pack is the transport layer: manifests, OA_DATA_DIR cache resolution, fetch,\n")
	out.append("and SHAKE256-256 verification. Typed loaders, grouped under audio, image,\n")
	out.append("text, and video, materialize their pack and expose an oa.data-compatible\n")
	out.append("sample contract. Fetch and decode run in Rust through the compiled\n")
	out.append("`oads._native` extension; the Python layer owns dataset semantics and\n")
	out.append("matrix upload.\n")
	out.append('"""\n\n')
	domains = sorted(schema["domains"])
	others = ["dataset", "pack"]
	imports = sorted(domains + others)
	out.append(f"from . import {', '.join(imports)}\n")
	for domain in domains:
		classes = sorted(p["class"] for p in packs if p["domain"] == domain)
		out.append(f"from .{domain} import {', '.join(classes)}\n")
	all_names = sorted([p["class"] for p in packs])
	exports = "\n".join(f'\t"{name}",' for name in all_names + imports)
	out.append(f"\n__all__ = [\n{exports}\n]\n")
	out.append(f'__version__ = "{version}"\n')
	return "".join(out)


