def load_schema() -> dict:
	return json.loads(SCHEMA.read_text())


def underscored(value: int) -> str:
	digits = str(value)
	groups = []
	while digits:
		groups.append(digits[-3:])
		digits = digits[:-3]
	return "_".join(reversed(groups))


def doc_lines(text: str, prefix: str = "///") -> list[str]:
	return [f"{prefix} {line}".rstrip() for line in text.split("\n")]


def rust_name(pack: dict) -> str:
	return pack.get("const_name", f"{pack['name'].upper()}_PACK")


def gen_loader(pack: dict) -> str:
	out = [RS_BANNER, ""]
	if pack.get("imagefolder"):
		out.append("use std::path::{Path, PathBuf};\n\n")
		out.append("use oa::data::{Dataset, Sample};\n")
		out.append("use oa::image::{Image, InterpolationMode};\n")
		out.append("use oa::matrix::{self, Matrix};\n")
		out.append("use oa::{Engine, Error, Result};\n\n")
		out.append("use crate::core::decode::Decoded;\n")
		out.append("use crate::core::pack::{self, FetchProgress, Pack, PackFile};\n")
		out.append("use crate::image::folder::{self, ImageIndex};\n\n")
	else:
		out.append("use oa::{Engine, Result};\n")
		if any("PathBuf" in field["type"] for field in pack["config"]):
			out.append("use std::path::PathBuf;\n")
		if pack["split"] and pack["split"]["kind"] == "idx":
			out.append("use crate::core::IdxSplit;\n")
		out.append("use crate::core::pack::{FetchProgress, Pack, PackFile};\n\n")

	# Manifest.
	out.append(f"pub(crate) const {rust_name(pack)}: Pack = Pack {{\n")
	out.append(f'\tname: "{pack["name"]}",\n')
	out.append(f'\tversion: "{pack["version"]}",\n')
	out.append(f'\tlicense: "{pack["license"]}",\n')
	out.append("\tfiles: &[\n")
	for entry in pack["files"]:
		out.append("\t\tPackFile {\n")
		out.append(f'\t\t\tname: "{entry["name"]}",\n')
		out.append(f'\t\t\tsize: {underscored(entry["size"])},\n')
		out.append(f'\t\t\tshake256: "{entry["shake256"]}",\n')
		if len(entry["urls"]) == 1:
			out.append(f'\t\t\turls: &["{entry["urls"][0]}"],\n')
		else:
			out.append("\t\t\turls: &[\n")
			for url in entry["urls"]:
				out.append(f'\t\t\t\t"{url}",\n')
			out.append("\t\t\t],\n")
		out.append("\t\t},\n")
	out.append("\t],\n};\n")

	# Pack consts.
	for const in pack.get("consts", []):
		out.append("\n")
		out.extend(line + "\n" for line in doc_lines(const["doc"]))
		out.append(f"pub const {const['name']}: {const['type']} = {const['value']};\n")

	# Split type.
	split = pack["split"]
	if split and split["kind"] == "idx":
		out.append("\n")
		out.extend(line + "\n" for line in doc_lines(split["doc"]))
		out.append(f"pub type {pack['class']}Split = IdxSplit;\n")
	elif split and split["kind"] == "enum":
		out.append("\n")
		out.extend(line + "\n" for line in doc_lines(split["doc"]))
		out.append("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]\n")
		out.append(f"pub enum {pack['class']}Split {{\n")
		for variant in split["variants"]:
			out.extend("\t" + line + "\n" for line in doc_lines(variant["doc"]))
			if variant.get("default"):
				out.append("\t#[default]\n")
			out.append(f"\t{variant['name']},\n")
		out.append("}\n")

	# Config.
	cls = pack["class"]
	out.append("\n")
	out.extend(
		line + "\n"
		for line in doc_lines(
			f"Load options for [`{cls}`][crate::{pack['domain']}::{pack['name']}::{cls}]."
		)
	)
	# `Default` derives only when every field default is the type's own
	# `Default::default()` value; enum/nonzero defaults need the manual impl.
	if all(field["default"] in ("None", "Default::default()") for field in pack["config"]):
		out.append("#[derive(Clone, Debug, Default)]\n")
	else:
		out.append("#[derive(Clone, Debug)]\n")
	out.append(f"pub struct {cls}Config {{\n")
	for field in pack["config"]:
		out.extend("\t" + line + "\n" for line in doc_lines(field["doc"]))
		out.append(f"\tpub {field['name']}: {field['type']},\n")
	out.append("}\n\n")
	if all(field["default"] in ("None", "Default::default()") for field in pack["config"]):
		pass
	else:
		out.append(f"impl Default for {cls}Config {{\n")
		out.append("\tfn default() -> Self {\n")
		out.append("\t\tSelf {\n")
		for field in pack["config"]:
			out.append(f"\t\t\t{field['name']}: {field['default']},\n")
		out.append("\t\t}\n\t}\n}\n\n")
	out.append(f"impl {cls}Config {{\n")
	out.append("\t/// Construct the record with its default state.\n")
	out.append("\t#[inline]\n\t#[must_use]\n")
	out.append("\tpub fn new() -> Self {\n")
	out.append("\t\tSelf::default()\n\t}\n}\n")

	# Engineless/explicit load family over handwritten load_with_progress_on.
	out.append(f"\nimpl super::{cls} {{\n")
	out.append("\t/// Decode the selected split and upload it on this thread's\n")
	out.append("\t/// default engine.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns an error when the default engine cannot be\n")
	out.append("\t/// initialized, plus the errors of\n")
	out.append("\t/// [`load_on`](Self::load_on).\n")
	out.append("\t#[inline]\n")
	out.append(f"\tpub fn load(config: &{cls}Config) -> Result<Self> {{\n")
	out.append("\t\tSelf::load_on(&Engine::current()?, config)\n")
	out.append("\t}\n\n")
	out.append("\t/// Decode the selected split and upload it on `engine`.\n")
	out.append("\t///\n")
	out.append("\t/// This is the [`load`](Self::load) contract evaluated on\n")
	out.append("\t/// `engine` instead of this thread's default engine.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns the errors of\n")
	out.append("\t/// [`load_with_progress_on`](Self::load_with_progress_on).\n")
	out.append("\t#[inline]\n")
	out.append(f"\tpub fn load_on(engine: &Engine, config: &{cls}Config) -> Result<Self> {{\n")
	out.append("\t\tSelf::load_with_progress_on(engine, config, &mut |_| true)\n")
	out.append("\t}\n\n")
	out.append("\t/// [`load`](Self::load) with a fetch progress callback.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns an error when the default engine cannot be\n")
	out.append("\t/// initialized, plus the errors of\n")
	out.append("\t/// [`load_with_progress_on`](Self::load_with_progress_on).\n")
	out.append("\t#[inline]\n")
	out.append("\tpub fn load_with_progress(\n")
	out.append(f"\t\tconfig: &{cls}Config,\n")
	out.append("\t\tprogress: &mut impl FnMut(FetchProgress) -> bool,\n")
	out.append("\t) -> Result<Self> {\n")
	out.append("\t\tSelf::load_with_progress_on(&Engine::current()?, config, progress)\n")
	out.append("\t}\n}\n")
	if pack.get("imagefolder"):
		out.append(gen_imagefolder_impl(pack))
	return "".join(out)


def gen_imagefolder_impl(pack: dict) -> str:
	cls = pack["class"]
	spec = pack["imagefolder"]
	roots = spec["roots"]
	files_map = spec.get("files")
	split = pack["split"]
	pack_const = rust_name(pack)
	out = []

	def key_lines(indent: str) -> list[str]:
		if not split:
			return [f'{indent}let split_key = "all";\n']
		arms = ",\n".join(
			f"{indent}\t{cls}Split::{v['name']} => \"{v['name'].lower()}\""
			for v in split["variants"]
		)
		return [
			f"{indent}let split_key = match config.split {{\n{arms},\n{indent}}};\n"
		]

	def files_lines(indent: str) -> list[str]:
		if not files_map:
			lines = [f"{indent}let members: &[&str] = &[\n"]
			lines += [f'{indent}\t"{entry["name"]}",\n' for entry in pack["files"]]
			lines.append(f"{indent}];\n")
			return lines
		if set(files_map) == {"_"}:
			lines = [f"{indent}let members: &[&str] = &[\n"]
			lines += [f'{indent}\t"{name}",\n' for name in files_map["_"]]
			lines.append(f"{indent}];\n")
			return lines
		arms = ",\n".join(
			f"{indent}\t{cls}Split::{variant} => &["
			+ ", ".join(f'"{name}"' for name in files_map[variant])
			+ "]"
			for variant in files_map
		)
		missing = [v["name"] for v in split["variants"] if v["name"] not in files_map]
		if missing:
			arms += ",\n" + ",\n".join(
				f"{indent}\t{cls}Split::{variant} => &[]" for variant in missing
			)
		return [
			f"{indent}let members: &[&str] = match config.split {{\n{arms},\n{indent}}};\n"
		]

	def root_lines(indent: str, target: str) -> list[str]:
		if set(roots) == {"_"}:
			root = roots["_"].rstrip("/")
			if not root or root == ".":
				return [f"{indent}let {target} = extracted.to_path_buf();\n"]
			return [f'{indent}let {target} = extracted.join("{root}");\n']
		arms = ",\n".join(
			f'{indent}\t{cls}Split::{variant} => "{roots[variant].rstrip("/")}"'
			for variant in roots
		)
		return [
			f"{indent}let {target} = extracted.join(match config.split {{\n{arms},\n{indent}}});\n"
		]

	index_call = (
		"ImageIndex::class_dirs(&index_root)?"
		if spec["labels"] == "classdirs"
		else "super::index(&index_root, config)?"
	)

	out.append("\n")
	out.extend(
		line + "\n"
		for line in doc_lines(
			f"Device-resident {pack['name']} dataset implementing [`oa::data::Dataset`].\n"
			"\n"
			"Members stay in the extracted pack cache; `get_item` lazily decodes\n"
			"one `[1, 3, H, W]` F32 NCHW image through [`oa::image`], resized to\n"
			"`config.size` when set. `labels()` is the resident `[N]` F32 class\n"
			"index matrix into [`classes`](Self::classes)."
		)
	)
	out.append(f"pub struct {cls} {{\n")
	out.append("\tpaths: Vec<PathBuf>,\n")
	out.append("\tlabels: Matrix,\n")
	out.append("\tclasses: Vec<String>,\n")
	out.append("\tsize: Option<(u32, u32)>,\n")
	out.append("\tengine: Engine,\n")
	out.append("}\n\n")

	out.append(f"impl {cls} {{\n")
	out.append("\t/// Fetch, verify, extract, and index the pack on the host.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns pack fetch/verification errors, archive decode errors,\n")
	out.append("\t/// and I/O errors while materializing the extracted cache.\n")
	out.append(f"\tpub fn decode(config: &{cls}Config) -> Result<Decoded> {{\n")
	out.append("\t\tSelf::decode_with_progress(config, &mut |_| true)\n")
	out.append("\t}\n\n")
	out.append("\t/// [`decode`](Self::decode) with a fetch progress callback.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns the errors of [`decode`](Self::decode), plus\n")
	out.append("\t/// `Cancelled` when `progress` aborts the fetch.\n")
	out.append("\tpub fn decode_with_progress(\n")
	out.append(f"\t\tconfig: &{cls}Config,\n")
	out.append("\t\tprogress: &mut impl FnMut(FetchProgress) -> bool,\n")
	out.append("\t) -> Result<Decoded> {\n")
	out.append("\t\tlet extracted = Self::materialize(config, progress)?;\n")
	out.append("\t\tlet index = Self::index_of(config, &extracted)?;\n")
	out.append("\t\tOk(Decoded {\n")
	out.append("\t\t\tmatrices: vec![index.labels()?],\n")
	out.append("\t\t\ttext: Some(index.paths_text(&extracted)?),\n")
	out.append("\t\t\tseq_len: 0,\n")
	out.append("\t\t})\n")
	out.append("\t}\n\n")

	out.append("\t/// [`load_on`](Self::load_on) with a fetch progress callback.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns the errors of [`load_on`](Self::load_on), plus\n")
	out.append("\t/// `Cancelled` when `progress` aborts the fetch.\n")
	out.append("\tpub fn load_with_progress_on(\n")
	out.append("\t\tengine: &Engine,\n")
	out.append(f"\t\tconfig: &{cls}Config,\n")
	out.append("\t\tprogress: &mut impl FnMut(FetchProgress) -> bool,\n")
	out.append("\t) -> Result<Self> {\n")
	out.append("\t\tlet decoded = Self::decode_with_progress(config, progress)?;\n")
	out.append('\t\tlet labels = decoded.upload("labels", engine)?;\n')
	out.append("\t\tlet index = Self::index_of(config, &Self::extracted_dir(config)?)?;\n")
	out.append("\t\tOk(Self {\n")
	out.append("\t\t\tpaths: index.paths,\n")
	out.append("\t\t\tlabels,\n")
	out.append("\t\t\tclasses: index.classes,\n")
	out.append("\t\t\tsize: config.size,\n")
	out.append("\t\t\tengine: engine.clone(),\n")
	out.append("\t\t})\n")
	out.append("\t}\n\n")

	out.append("\t/// Class names in label-index order.\n")
	out.append("\t#[must_use]\n")
	out.append("\tpub fn classes(&self) -> &[String] {\n")
	out.append("\t\t&self.classes\n\t}\n\n")
	out.append("\t/// `[N]` F32 class-index matrix on the owning engine.\n")
	out.append("\t#[must_use]\n")
	out.append("\tpub const fn labels(&self) -> &Matrix {\n")
	out.append("\t\t&self.labels\n\t}\n\n")
	out.append("\t/// Number of indexed samples.\n")
	out.append("\t#[must_use]\n")
	out.append("\tpub fn count(&self) -> usize {\n")
	out.append("\t\tself.paths.len()\n\t}\n\n")
	out.append("\t/// Extracted image path for row `index`.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns `out_of_range` when `index` is outside the dataset.\n")
	out.append("\tpub fn path(&self, index: i64) -> Result<&Path> {\n")
	out.append("\t\tif index < 0 || index >= self.paths.len() as i64 {\n")
	out.append(f'\t\t\treturn Err(Error::out_of_range("{pack["name"]} index is outside the dataset"));\n')
	out.append("\t\t}\n")
	out.append("\t\tOk(&self.paths[index as usize])\n")
	out.append("\t}\n\n")
	out.append("\t/// Lazily decode image `index` to a `[1, 3, H, W]` F32 NCHW\n")
	out.append("\t/// image on the owning engine, resized to `config.size` when\n")
	out.append("\t/// set.\n")
	out.append("\t///\n")
	out.append("\t/// # Errors\n")
	out.append("\t///\n")
	out.append("\t/// Returns `out_of_range` for an out-of-range index and the\n")
	out.append("\t/// [`oa::image`] decode/resize errors for the member.\n")
	out.append("\tpub fn image(&self, index: i64) -> Result<Image> {\n")
	out.append("\t\tlet image = folder::decode(&self.engine, self.path(index)?)?;\n")
	out.append("\t\tmatch self.size {\n")
	out.append("\t\t\tSome((width, height)) => {\n")
	out.append("\t\t\t\toa::image::resize(&image, width, height, InterpolationMode::Bilinear)\n")
	out.append("\t\t\t}\n")
	out.append("\t\t\tNone => Ok(image),\n")
	out.append("\t\t}\n")
	out.append("\t}\n\n")

	out.append(f"\tfn pack_dir(config: &{cls}Config) -> Result<PathBuf> {{\n")
	out.append("\t\tlet root = match &config.cache_dir {\n")
	out.append("\t\t\tSome(dir) => dir.clone(),\n")
	out.append("\t\t\tNone => pack::data_root()?,\n")
	out.append("\t\t};\n")
	out.append(f'\t\tOk(root.join("{pack["name"]}").join("{pack["version"]}"))\n')
	out.append("\t}\n\n")
	out.append(f"\tfn extracted_dir(config: &{cls}Config) -> Result<PathBuf> {{\n")
	out.append('\t\tOk(Self::pack_dir(config)?.join("extracted"))\n')
	out.append("\t}\n\n")
	out.append("\tfn materialize(\n")
	out.append(f"\t\tconfig: &{cls}Config,\n")
	out.append("\t\tprogress: &mut impl FnMut(FetchProgress) -> bool,\n")
	out.append("\t) -> Result<PathBuf> {\n")
	out.append("\t\tlet root = match &config.cache_dir {\n")
	out.append("\t\t\tSome(dir) => dir.clone(),\n")
	out.append("\t\t\tNone => pack::data_root()?,\n")
	out.append("\t\t};\n")
	out.append(f"\t\tlet dir = pack::ensure_pack_with_progress(&{pack_const}, &root, progress)?;\n")
	out.append('\t\tlet extracted = dir.join("extracted");\n')
	per_split = bool(files_map) and set(files_map) != {"_"}
	if per_split:
		out.extend(key_lines("\t\t"))
		out.append('\t\tlet done = extracted.join(format!(".done_{split_key}"));\n')
	else:
		out.append('\t\tlet done = extracted.join(".done_all");\n')
	out.append("\t\tif done.exists() {\n")
	out.append("\t\t\treturn Ok(extracted);\n")
	out.append("\t\t}\n")
	out.extend(files_lines("\t\t"))
	if per_split:
		out.append("\t\tlet target = extracted.join(split_key);\n")
		out.append("\t\tfor member in members {\n")
		out.append("\t\t\tfolder::extract_images(&dir.join(member), &target)?;\n")
		out.append("\t\t}\n")
	else:
		out.append("\t\tfor member in members {\n")
		out.append("\t\t\tfolder::extract_images(&dir.join(member), &extracted)?;\n")
		out.append("\t\t}\n")
	out.append('\t\tstd::fs::write(&done, b"done")\n')
	out.append(f'\t\t\t.map_err(|error| Error::io("write {pack["name"]} extract marker", error))?;\n')
	out.append("\t\tOk(extracted)\n")
	out.append("\t}\n\n")
	out.append("\tfn index_of(\n")
	uses_config = bool(split) or spec["labels"] != "classdirs"
	param = "config" if uses_config else "_config"
	out.append(f"\t\t{param}: &{cls}Config,\n")
	out.append("\t\textracted: &Path,\n")
	out.append("\t) -> Result<ImageIndex> {\n")
	out.extend(root_lines("\t\t", "index_root"))
	out.append(f"\t\tlet index = {index_call};\n")
	out.extend(key_lines("\t\t"))
	out.append('\t\tlet classes = extracted.join(format!(".classes_{split_key}"));\n')
	out.append("\t\tif !classes.exists() {\n")
	out.append("\t\t\tstd::fs::create_dir_all(extracted)\n")
	out.append('\t\t\t\t.map_err(|error| Error::io("create extracted root", error))?;\n')
	out.append('\t\t\tstd::fs::write(&classes, index.classes.join("\\n"))\n')
	out.append(f'\t\t\t\t.map_err(|error| Error::io("write {pack["name"]} class table", error))?;\n')
	out.append("\t\t}\n")
	out.append("\t\tOk(index)\n")
	out.append("\t}\n")
	out.append("}\n\n")

	out.append(f"impl Dataset for {cls} {{\n")
	out.append("\tfn len(&self) -> i64 {\n")
	out.append("\t\ti64::try_from(self.paths.len()).unwrap_or(i64::MAX)\n")
	out.append("\t}\n\n")
	out.append("\tfn get_item(&self, index: i64) -> Result<Matrix> {\n")
	out.append("\t\tself.image(index)?.into_matrix().squeeze(0)\n")
	out.append("\t}\n\n")
	out.append("\tfn get_sample(&self, index: i64) -> Result<Sample> {\n")
	out.append("\t\tlet x = self.get_item(index)?;\n")
	out.append("\t\tlet y = matrix::slice(&self.labels, 0, index, index + 1)?;\n")
	out.append("\t\tOk(Sample::new_with_label(x, y))\n")
	out.append("\t}\n")
	out.append("}\n")
	return "".join(out)


def dispatch_expr(pack: dict, field: dict) -> str:
	generic = field.get("generic")
	if generic == "split":
		if pack["split"]["kind"] == "idx":
			return "config.split"
		mapping = pack["split"]["dispatch"]
		arms = ",\n\t\t\t\t".join(
			f"IdxSplit::{src} => crate::{pack['domain']}::{pack['name']}::{pack['class']}Split::{dst}"
			for src, dst in mapping.items()
		)
		if set(mapping) != {"Train", "Test", "Validation"}:
			arms += (
				',\n\t\t\t\t_ => return Err(Error::invalid_argument("'
				f"{pack['name']} does not carry that IdxSplit variant"
				'"))'
			)
		return "match config.split {\n\t\t\t\t" + arms + ",\n\t\t\t}"
	if generic is None:
		return field["dispatch"]
	return GENERIC_EXPR[generic]


def gen_dispatch(packs: list[dict]) -> str:
	out = [RS_BANNER, ""]
	out.append("use oa::{Error, Result};\n\n")
	out.append("use crate::core::IdxSplit;\n")
	out.append("use crate::core::decode::{DecodeConfig, Decoded};\n")
	out.append("use crate::core::pack::{FetchProgress, Pack};\n\n")

	out.append("pub(crate) fn manifest_of(name: &str) -> Result<&'static Pack> {\n")
	out.append("\tmatch name {\n")
	for pack in packs:
		out.append(
			f'\t\t"{pack["name"]}" => Ok(&crate::{pack["domain"]}::{pack["name"]}::{rust_name(pack)}),\n'
		)
	out.append("\t\t_ => Err(Error::invalid_argument(format!(\n")
	out.append('\t\t\t"unknown dataset pack \'{name}\'"\n')
	out.append("\t\t))),\n\t}\n}\n\n")

	out.append("pub(crate) fn load_of(\n")
	out.append("\tname: &str,\n")
	out.append("\tconfig: &DecodeConfig,\n")
	out.append("\tprogress: &mut impl FnMut(FetchProgress) -> bool,\n")
	out.append(") -> Result<Decoded> {\n")
	out.append("\tmatch name {\n")
	for pack in packs:
		cls = pack["class"]
		call = "decode_with_progress" if pack["progress"] else "decode"
		out.append(
			f'\t\t"{pack["name"]}" => crate::{pack["domain"]}::{pack["name"]}::{cls}::{call}(\n'
		)
		out.append(f"\t\t\t&crate::{pack['domain']}::{pack['name']}::{cls}Config {{\n")
		for field in pack["config"]:
			out.append(f"\t\t\t\t{field['name']}: {dispatch_expr(pack, field)},\n")
		out.append("\t\t\t},\n")
		if pack["progress"]:
			out.append("\t\t\tprogress,\n")
		out.append("\t\t),\n")
	out.append("\t\t_ => Err(Error::invalid_argument(format!(\n")
	out.append('\t\t\t"unknown dataset pack \'{name}\'"\n')
	out.append("\t\t))),\n\t}\n}\n")
	return "".join(out)


def exported_names(pack: dict) -> list[str]:
	names = [pack["class"], f"{pack['class']}Config"]
	if pack["split"]:
		names.append(f"{pack['class']}Split")
	names.extend(pack.get("extra_exports", []))
	for const in pack.get("consts", []):
		if const.get("export"):
			names.append(const["name"])
	return sorted(names)


def gen_facade(
	domain: str, doc: str, packs: list[dict], internal_modules: list[str] | None = None
) -> str:
	internal_modules = internal_modules or []
	out = [RS_BANNER, ""]
	for line in doc.split("\n"):
		prefix = "//!" if line.startswith("//!") else "//!"
		out.append(f"{prefix} {line.removeprefix('//!').lstrip()}".rstrip() + "\n")
	out.append("\n")
	for module in internal_modules:
		out.append(f"pub(crate) mod {module};\n")
	for pack in packs:
		out.append(f"pub mod {pack['name']};\n")
	out.append("\n")
	for pack in packs:
		names = ", ".join(exported_names(pack))
		out.append(f"pub use {pack['name']}::{{{names}}};\n")
	return "".join(out)


def gen_lib_rs(schema: dict, packs: list[dict]) -> str:
	out = [RS_BANNER, ""]
	out.append("//! Realm dataset packs and typed loaders for OA.\n")
	out.append("//!\n")
	out.append("//! [`core`] is the machinery layer: [`pack`]'s immutable manifests,\n")
	out.append("//! `OA_DATA_DIR` cache resolution, resumable fetch, SHAKE256-256\n")
	out.append("//! verification, host-side [`decode`], and the internal format readers.\n")
	out.append("//! Each typed loader — grouped by domain under [`audio`], [`image`],\n")
	out.append("//! [`tabular`], [`text`], and [`video`] — materializes its pack and\n")
	out.append("//! implements [`oa::data::Dataset`], so [`oa::data::DataLoader`],\n")
	out.append("//! [`oa::data::collate`], and subset/split operations work unchanged.\n\n")
	out.append("pub mod core;\n\n")
	out.append("pub use core::{decode, pack};\n\n")
	domains = sorted(schema["domains"])
	for module in domains:
		out.append(f"pub mod {module};\n")
	out.append("\n")

	for domain in domains:
		names = []
		for pack in packs:
			if pack["domain"] == domain:
				names.extend(exported_names(pack))
		out.append(f"pub use {domain}::{{{', '.join(sorted(names))}}};\n")
	for module, names in CORE_EXPORTS:
		out.append(f"pub use {module}::{{{', '.join(names)}}};\n")
	return "".join(out)


def py_const_expr(const: dict) -> str | None:
	if const["type"].startswith("[&str"):
		names = re.findall(r'"([^"]+)"', const["value"])
		return "(" + ", ".join(f'"{n}"' for n in names) + ")"
	return None


def gen_python_imagefolder(pack: dict) -> str:
	py = pack["python"]
	doc = py["doc"]
	header = f'"""{doc}"""\n' if "\n" not in doc else f'"""{doc}\n"""\n'
	cls = pack["class"]
	out = [header + "\n"]
	out.append("from array import array\n")
	out.append("from pathlib import Path\n\n")
	out.append("import oa\n\n")
	out.append("from .. import _native\n")
	out.append("from .._progress import resolve\n")
	out.append("from ..dataset import matrix\n")
	out.append(f'\nPACK = _native.pack_manifest("{pack["name"]}")\n')
	for name in py.get("consts", []):
		const = next(c for c in pack["consts"] if c["name"] == name)
		expr = py_const_expr(const)
		if expr:
			out.append(f"{name} = {expr}\n")
	out.append(f"\n\nclass {cls}:\n")
	out.append('\t"""Lazy [1, 3, H, W] f32 NCHW images + [N] class labels."""\n\n')
	out.append("\tdef __init__(self, labels, label_list, paths, classes, size, engine):\n")
	out.append("\t\tself._labels = labels\n")
	out.append("\t\tself._label_list = label_list\n")
	out.append("\t\tself._paths = paths\n")
	out.append("\t\tself._classes = classes\n")
	out.append("\t\tself._size = size\n")
	out.append("\t\tself._engine = engine\n\n")
	out.append("\t@classmethod\n")
	out.append("\tdef load(\n")
	out.append("\t\tcls,\n")
	out.append('\t\tengine: "oa.Engine | None" = None,\n')
	out.append('\t\tsplit: str = "train",\n')
	out.append("\t\tsize=None,\n")
	out.append("\t\tcache_dir=None,\n")
	out.append("\t\tprogress=True,\n")
	out.append(f"\t) -> \"{cls}\":\n")
	out.append('\t\t"""Fetch, verify, extract, and index the pack.\n\n')
	out.append("\t\tMembers stay in the extracted cache and decode lazily per\n")
	out.append("\t\tsample. `size=(width, height)` resizes each image on access;\n")
	out.append("\t\tprogress=True renders the download bar; a callable receives\n")
	out.append("\t\t(file, fetched, total) samples instead.\n")
	out.append('\t\t"""\n')
	out.append("\t\tfields = _native.load(\n")
	out.append('\t\t\tPACK["name"],\n')
	out.append("\t\t\tsplit=split,\n")
	out.append("\t\t\tcache_dir=str(Path(cache_dir)) if cache_dir else None,\n")
	out.append("\t\t\tprogress=resolve(progress),\n")
	out.append("\t\t)\n")
	out.append("\t\tresolved = engine if engine is not None else oa.Engine.current()\n")
	out.append("\t\troot = Path(cache_dir) if cache_dir else Path(_native.data_root())\n")
	out.append('\t\textracted = root / PACK["name"] / PACK["version"] / "extracted"\n')
	out.append('\t\tpaths = [extracted / line for line in fields["text"].splitlines()]\n')
	if pack["split"]:
		out.append('\t\tclasses = (extracted / f".classes_{split}").read_text().splitlines()\n')
	else:
		out.append('\t\tclasses = (extracted / ".classes_all").read_text().splitlines()\n')
	out.append('\t\tlabel_list = [int(v) for v in array("f", fields["labels"]["data"])]\n')
	out.append("\t\treturn cls(\n")
	out.append('\t\t\tmatrix(fields["labels"], resolved),\n')
	out.append("\t\t\tlabel_list,\n")
	out.append("\t\t\tpaths,\n")
	out.append("\t\t\tclasses,\n")
	out.append("\t\t\tsize,\n")
	out.append("\t\t\tresolved,\n")
	out.append("\t\t)\n\n")
	out.append("\tdef __len__(self) -> int:\n")
	out.append("\t\treturn len(self._paths)\n\n")
	out.append("\t@property\n")
	out.append('\tdef labels(self) -> "oa.Matrix":\n')
	out.append('\t\t"""[N] f32 class indices into `classes`."""\n')
	out.append("\t\treturn self._labels\n\n")
	out.append("\t@property\n")
	out.append("\tdef classes(self) -> list:\n")
	out.append('\t\t"""Class names in label-index order."""\n')
	out.append("\t\treturn self._classes\n\n")
	out.append("\tdef path(self, index: int) -> Path:\n")
	out.append('\t\t"""Extracted image path for row `index`."""\n')
	out.append("\t\treturn self._paths[index]\n\n")
	out.append("\tdef label(self, index: int) -> int:\n")
	out.append('\t\t"""Class index for row `index` (host-side, no readback)."""\n')
	out.append("\t\treturn self._label_list[index]\n\n")
	out.append("\tdef image(self, index: int) -> \"oa.Image\":\n")
	out.append('\t\t"""Lazily decode image `index` to a [1, 3, H, W] f32 NCHW image."""\n')
	out.append("\t\timage = oa.image.decode_file(\n")
	out.append('\t\t\tstr(self._paths[index]), "rgb", self._engine\n')
	out.append("\t\t)\n")
	out.append("\t\tif self._size is not None:\n")
	out.append("\t\t\twidth, height = self._size\n")
	out.append("\t\t\treturn oa.image.resize(image, width, height)\n")
	out.append("\t\treturn image\n\n")
	out.append("\tdef get_item(self, index: int) -> \"oa.Matrix\":\n")
	out.append('\t\t"""Lazily decode image `index` as a [3, H, W] matrix."""\n')
	out.append("\t\titem = self.image(index).as_matrix()\n")
	out.append("\t\treturn item.reshape(item.shape[1:])\n\n")
	out.append("\tdef get_sample(self, index: int):\n")
	out.append('\t\t"""(image, class label) pair for one row."""\n')
	out.append("\t\treturn self.get_item(index), self._labels.slice(0, index, index + 1)\n")
	return "".join(out)


def gen_python_loader(pack: dict) -> str | None:
	py = pack["python"]
	if py["contract"] == "imagefolder":
		return gen_python_imagefolder(pack)
	if py["contract"] != "matrix":
		return None
	doc = py["doc"]
	header = f'"""{doc}"""\n' if "\n" not in doc else f'"""{doc}\n"""\n'
	out = [header + "\n"]
	unsplit = py.get("unsplit", False)
	if unsplit:
		out.append("from pathlib import Path\n\n")
		out.append("from .. import _native\n")
		out.append("from .._progress import resolve\n")
		out.append("from ..dataset import MatrixDataset, matrix\n")
	else:
		out.append("from .. import _native\n")
		out.append("from ..dataset import MatrixDataset\n")
	out.append(f"\n\nclass {pack['class']}(MatrixDataset):\n")
	out.append(f'\tPACK = _native.pack_manifest("{pack["name"]}")\n')
	if pack["python"]["feature"] != "images":
		out.append(f'\tFEATURE = "{py["feature"]}"\n')
	if py.get("label", "labels") != "labels":
		out.append(f'\tLABEL = "{py["label"]}"\n')
	for name in py.get("consts", []):
		const = next(c for c in pack["consts"] if c["name"] == name)
		expr = py_const_expr(const)
		if expr:
			out.append(f"\t{name} = {expr}\n")
	if unsplit:
		load_doc = py.get(
			"load_doc",
			"Fetch, verify, decode, and upload the full pack.\n\n"
			"\tnormalize=True scales features into the pack's canonical unit\n"
			"\trange; normalize=False keeps raw f32 values. progress=True renders\n"
			"\tthe download bar.",
		)
		out.append(
			f"""
	@classmethod
	def load(cls, engine=None, cache_dir=None, normalize: bool = True, progress=True):
		\"\"\"{load_doc}
		\"\"\"
		fields = _native.load(
			cls.PACK["name"],
			# The pack carries one unsplit set; the native split argument
			# only accepts train/test and is ignored for this loader.
			split="train",
			normalize=normalize,
			cache_dir=str(Path(cache_dir)) if cache_dir else None,
			progress=resolve(progress),
		)
		return cls(
			matrix(fields[cls.FEATURE], engine),
			matrix(fields[cls.LABEL], engine),
			"all",
		)
"""
		)
	feature = py["feature"]
	feature_doc = py.get(
		"feature_doc", f"Full {feature} matrix on the owning engine; alias of `x`."
	)
	out.append("\n\t@property\n")
	out.append(f"\tdef {feature}(self):\n")
	out.append(f'\t\t"""{feature_doc}"""\n')
	out.append("\t\treturn self.x\n")
	label = py.get("label")
	if label and label != "labels":
		label_doc = py.get(
			"label_doc", f"Full {label} matrix on the owning engine; alias of `labels`."
		)
		out.append("\n\t@property\n")
		out.append(f"\tdef {label}(self):\n")
		out.append(f'\t\t"""{label_doc}"""\n')
		out.append("\t\treturn self.labels\n")
	return "".join(out)


