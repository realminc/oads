def rustfmt(content: str) -> str:
	import subprocess

	edition = re.search(
		r'^edition = "([^"]+)"', (ROOT / "Cargo.toml").read_text(), re.M
	).group(1)
	result = subprocess.run(
		["rustfmt", "--emit", "stdout", "--edition", edition],
		input=content,
		capture_output=True,
		text=True,
		cwd=ROOT,
	)
	if result.returncode != 0:
		raise RuntimeError(f"rustfmt failed on generated output:\n{result.stderr}")
	return result.stdout


def pyproject_version() -> str:
	text = (ROOT / "pyproject.toml").read_text()
	return re.search(r'^version = "([^"]+)"', text, re.M).group(1)


def outputs(schema: dict) -> dict[str, str]:
	packs = schema["packs"]
	files = {}

	for pack in packs:
		domain, name = pack["domain"], pack["name"]
		files[f"src/rs/{domain}/{name}.gen.rs"] = rustfmt(gen_loader(pack))
		py_src = gen_python_loader(pack)
		if py_src:
			files[f"src/py/oads/{domain}/{name}.py"] = py_src

	files["src/rs/core/decode_dispatch.gen.rs"] = rustfmt(gen_dispatch(packs))
	files["src/rs/lib.rs"] = rustfmt(gen_lib_rs(schema, packs))
	for domain, record in schema["domains"].items():
		files[f"src/rs/{domain}.rs"] = rustfmt(
			gen_facade(
				domain,
				record["doc"],
				[p for p in packs if p["domain"] == domain],
				record.get("internal_modules", []),
			)
		)
		files[f"src/py/oads/{domain}/__init__.py"] = gen_python_init(
			domain, record["py_doc"], [p for p in packs if p["domain"] == domain]
		)
	files["src/py/oads/__init__.py"] = gen_python_root(
		schema, packs, pyproject_version()
	)
	files["license/README.md"] = gen_license_readme(packs)
	files["docs/datasets.md"] = gen_datasets_md(schema, packs)
	return files


def main() -> int:
	schema = load_schema()
	check = "--check" in sys.argv
	generated = outputs(schema)

	drift = []
	for rel, content in generated.items():
		path = ROOT / rel
		if check:
			if not path.exists() or path.read_text() != content:
				drift.append(rel)
		else:
			path.parent.mkdir(parents=True, exist_ok=True)
			if not path.exists() or path.read_text() != content:
				path.write_text(content)
				print(f"wrote {rel}")

	if check:
		tracked = set(generated)
		extra = [
			str(path.relative_to(ROOT))
			for path in ROOT.rglob("*.gen.rs")
			if str(path.relative_to(ROOT)) not in tracked
		]
		for rel in extra:
			print(f"stale generated file: {rel}")
			drift.append(rel)
		if drift:
			print("generated output is stale:")
			for rel in drift:
				print(f"  {rel}")
			return 1
		print("generated output is current")
	return 0


